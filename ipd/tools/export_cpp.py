#!/usr/bin/env python3
"""Unified C++ weight-header exporter.

Examples::

    python3 -m ipd export --arch mlp
    python3 -m ipd export --arch gru
    python3 -m ipd export --weights weights/rl_policy_weights.json \
        --out cpp/rl_policy_weights.hpp
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Sequence

from ipd.paths import cpp_path, weights_path


def fmt(x: float) -> str:
    return f"{float(x):.9g}f"


def array(values, per_line: int = 8) -> str:
    pieces = [fmt(x) for x in values]
    lines = [", ".join(pieces[i:i + per_line])
             for i in range(0, len(pieces), per_line)]
    return ",\n    ".join(lines)


def matrix(rows, per_line: int = 8) -> str:
    body = ",\n    ".join("{" + array(row, per_line) + "}" for row in rows)
    return "{\n    " + body + "\n}"


def tensor(layers, per_line: int = 8) -> str:
    body = ",\n    ".join(matrix(layer, per_line) for layer in layers)
    return "{\n    " + body + "\n}"


def _write(path: str, text: str) -> None:
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"written {path} ({len(text)} bytes)")


def export_mlp(weights: str, out: str) -> None:
    with open(weights, encoding="utf-8") as fh:
        w = json.load(fh)
    layers = w["layers"]
    if len(layers) != 3:
        raise SystemExit(f"expected 3 linear layers, got {len(layers)}")
    n_features = int(w["n_features"])
    n0 = len(layers[0]["w"])
    n1 = len(layers[1]["w"])

    lines = [
        "// Auto-generated by ipd.tools.export_cpp.  Do not edit by hand.",
        "#pragma once",
        "",
        "namespace neural_policy_weights {",
        f"constexpr int N_FEATURES = {n_features};",
        f"constexpr int N_HIDDEN0 = {n0};",
        f"constexpr int N_HIDDEN1 = {n1};",
        f"constexpr double TEMPERATURE = {float(w.get('temperature', 1.0)):.9g};",
        f"constexpr bool SAFE = {'true' if w.get('safe', True) else 'false'};",
        "",
        "static const float MEAN[N_FEATURES] = {",
        "    " + array(w["feature_mean"], 10),
        "};",
        "",
        "static const float STD[N_FEATURES] = {",
        "    " + array(w["feature_std"], 10),
        "};",
        "",
        f"static const float W0[N_HIDDEN0][N_FEATURES] = "
        + matrix(layers[0]["w"]) + ";",
        "",
        "static const float B0[N_HIDDEN0] = {",
        "    " + array(layers[0]["b"], 8),
        "};",
        "",
        f"static const float W1[N_HIDDEN1][N_HIDDEN0] = "
        + matrix(layers[1]["w"]) + ";",
        "",
        "static const float B1[N_HIDDEN1] = {",
        "    " + array(layers[1]["b"], 8),
        "};",
        "",
        "static const float W2[N_HIDDEN1] = {",
        "    " + array(layers[2]["w"][0], 8),
        "};",
        "",
        "static const float B2 = " + fmt(layers[2]["b"][0]) + ";",
        "",
        "}  // namespace neural_policy_weights",
        "",
    ]
    _write(out, "\n".join(lines))


def export_gru(weights: str, out: str) -> None:
    with open(weights, encoding="utf-8") as fh:
        w = json.load(fh)
    if w.get("format") != "ipd-gru-policy-v1":
        raise SystemExit(f"unexpected format: {w.get('format')}")
    n_features = int(w["n_features"])
    hidden = int(w["hidden"])
    num_layers = int(w["num_layers"])
    layers = w["gru"]
    if len(layers) != num_layers:
        raise SystemExit("num_layers does not match gru layer list")
    if num_layers != 1:
        raise SystemExit(
            "the C++ GRU port currently supports one layer; "
            "train with --layers 1 or use the Python GRUPolicy")
    for i, layer in enumerate(layers):
        if len(layer["weight_ih"]) != 3 * hidden:
            raise SystemExit(f"layer {i}: expected 3*hidden gate rows")
        if len(layer["weight_hh"]) != 3 * hidden:
            raise SystemExit(f"layer {i}: expected 3*hidden hidden rows")
    if len(w["head"]) != 2:
        raise SystemExit("expected a 2-layer MLP head")
    if len(w["head"][0]["w"]) != hidden or len(w["head"][0]["w"][0]) != hidden:
        raise SystemExit("head hidden layer shape mismatch")
    if len(w["head"][1]["w"]) != 1 or len(w["head"][1]["w"][0]) != hidden:
        raise SystemExit("head output layer shape mismatch")

    lines = [
        "// Auto-generated by ipd.tools.export_cpp.  Do not edit by hand.",
        "#pragma once",
        "",
        "namespace gru_policy_weights {",
        f"constexpr int N_FEATURES = {n_features};",
        f"constexpr int HIDDEN = {hidden};",
        f"constexpr int NUM_LAYERS = {num_layers};",
        f"constexpr double TEMPERATURE = {float(w.get('temperature', 1.0)):.9g};",
        "",
        "static const float MEAN[N_FEATURES] = {",
        "    " + array(w["feature_mean"], 10),
        "};",
        "",
        "static const float STD[N_FEATURES] = {",
        "    " + array(w["feature_std"], 10),
        "};",
        "",
        f"static const float W_IH[NUM_LAYERS][3 * HIDDEN][N_FEATURES] = "
        + tensor([layer["weight_ih"] for layer in layers]) + ";",
        "",
        f"static const float W_HH[NUM_LAYERS][3 * HIDDEN][HIDDEN] = "
        + tensor([layer["weight_hh"] for layer in layers]) + ";",
        "",
        "static const float B_IH[NUM_LAYERS][3 * HIDDEN] = {",
        ",\n    ".join("{" + array(layer["bias_ih"], 8) + "}" for layer in layers),
        "};",
        "",
        "static const float B_HH[NUM_LAYERS][3 * HIDDEN] = {",
        ",\n    ".join("{" + array(layer["bias_hh"], 8) + "}" for layer in layers),
        "};",
        "",
        "static const float HEAD_W0[HIDDEN][HIDDEN] = "
        + matrix(w["head"][0]["w"]) + ";",
        "",
        "static const float HEAD_B0[HIDDEN] = {",
        "    " + array(w["head"][0]["b"], 8),
        "};",
        "",
        "static const float HEAD_W1[HIDDEN] = {",
        "    " + array(w["head"][1]["w"][0], 8),
        "};",
        "",
        "static const float HEAD_B1 = " + fmt(w["head"][1]["b"][0]) + ";",
        "",
        "}  // namespace gru_policy_weights",
        "",
    ]
    _write(out, "\n".join(lines))


def _detect_arch(weights: str) -> str:
    with open(weights, encoding="utf-8") as fh:
        fmt_name = json.load(fh).get("format")
    if fmt_name == "ipd-gru-policy-v1":
        return "gru"
    if fmt_name == "ipd-neural-policy-v1":
        return "mlp"
    raise SystemExit(f"cannot infer C++ exporter for format {fmt_name!r}; "
                     "pass --arch")


def build_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(description="Export policy weights to C++ headers.")
    ap.add_argument("--arch", default="auto", choices=("auto", "mlp", "gru"))
    ap.add_argument("--weights", default=None)
    ap.add_argument("--out", default=None)
    return ap


def main(argv: Sequence[str] | None = None) -> int:
    ap = build_parser()
    args = ap.parse_args(argv)
    if args.weights is None:
        args.weights = weights_path(
            "gru_policy_weights.json" if args.arch == "gru"
            else "neural_policy_weights.json")
    arch = _detect_arch(args.weights) if args.arch == "auto" else args.arch
    if args.out is None:
        args.out = cpp_path(
            "gru_policy_weights.hpp" if arch == "gru"
            else "neural_policy_weights.hpp")
    if arch == "gru":
        export_gru(args.weights, args.out)
    else:
        export_mlp(args.weights, args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
