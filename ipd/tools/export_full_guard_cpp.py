#!/usr/bin/env python3
"""Export the deployable MLP used by the C++ RL-FullGuard policy.

The generated header contains a single ``rl_full_guard_weights`` namespace
with the standard 85-feature 160/128 MLP layout.

Example::

    python3 -m ipd.tools.export_full_guard_cpp \
      --weights weights/rl_policy_weights_v5_ft_complex.json \
      --out cpp/rl_full_guard_weights.hpp
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from .export_switch_cpp import _namespace


def export_full_guard(weights: str, out: str) -> None:
    with open(weights, encoding="utf-8") as fh:
        data = json.load(fh)
    lines = [
        "// Auto-generated by ipd.tools.export_full_guard_cpp.  Do not edit by hand.",
        "#pragma once",
        "",
    ]
    if int(data.get("n_features", 85)) > 85:
        lines += ["#define IPD_FEATURES_V2 1", ""]
    lines += _namespace("rl_full_guard_weights", data)
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join(lines)
    Path(out).write_text(text, encoding="utf-8")
    print(f"written {out} ({len(text)} bytes)")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--weights", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)
    export_full_guard(args.weights, args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
