#!/usr/bin/env python3
"""Export two deployable MLPs for the C++ RL-Switch policy.

The generated header contains two namespaces, ``rl_switch_base`` and
``rl_switch_alt``.  ``cpp/policies/rl_switch_policy.hpp`` consumes them and
implements the narrow early-switch rule.

Example::

    python3 -m ipd.tools.export_switch_cpp \
      --base weights/rl_policy_weights_wide160.json \
      --alt weights/rl_policy_weights_repair.json \
      --out cpp/rl_switch_weights.hpp
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from .export_cpp import array, fmt, matrix


def _namespace(name: str, data: dict) -> list[str]:
    layers = data.get("layers") or []
    if len(layers) != 3:
        raise SystemExit(f"{name}: expected 3 linear layers, got {len(layers)}")
    nf = int(data["n_features"])
    h0 = len(layers[0]["w"])
    h1 = len(layers[1]["w"])
    lines = [
        f"namespace {name} {{",
        f"constexpr int N_FEATURES = {nf};",
        f"constexpr int N_HIDDEN0 = {h0};",
        f"constexpr int N_HIDDEN1 = {h1};",
        f"constexpr double TEMPERATURE = {float(data.get('temperature', 1.0)):.9g};",
        f"constexpr bool SAFE = {'true' if data.get('safe', True) else 'false'};",
        "",
        "static const float MEAN[N_FEATURES] = {",
        "    " + array(data["feature_mean"], 10),
        "};",
        "",
        "static const float STD[N_FEATURES] = {",
        "    " + array(data["feature_std"], 10),
        "};",
        "",
        f"static const float W0[N_HIDDEN0][N_FEATURES] = "
        + matrix(layers[0]["w"]) + ";",
        "",
        "static const float B0[N_HIDDEN0] = {",
        "    " + array(layers[0]["b"], 8),
        "};",
        "",
        f"static const float W1[N_HIDDEN1][N_HIDDEN0] = "
        + matrix(layers[1]["w"]) + ";",
        "",
        "static const float B1[N_HIDDEN1] = {",
        "    " + array(layers[1]["b"], 8),
        "};",
        "",
        "static const float W2[N_HIDDEN1] = {",
        "    " + array(layers[2]["w"][0], 8),
        "};",
        "",
        "static const float B2 = " + fmt(layers[2]["b"][0]) + ";",
        "",
        f"}}  // namespace {name}",
        "",
    ]
    return lines


def export_switch(base: str, alt: str, out: str) -> None:
    with open(base, encoding="utf-8") as fh:
        base_data = json.load(fh)
    with open(alt, encoding="utf-8") as fh:
        alt_data = json.load(fh)
    lines = [
        "// Auto-generated by ipd.tools.export_switch_cpp.  Do not edit by hand.",
        "#pragma once",
        "",
        "#define IPD_FEATURES_V2 1" if int(base_data.get("n_features", 85)) > 85 else "",
        "",
    ]
    lines += _namespace("rl_switch_base", base_data)
    lines += _namespace("rl_switch_alt", alt_data)
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text("\n".join(lines), encoding="utf-8")
    print(f"written {out} ({len('\n'.join(lines))} bytes)")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--base", required=True)
    ap.add_argument("--alt", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)
    export_switch(args.base, args.alt, args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
