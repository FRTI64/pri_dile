#!/usr/bin/env python3
"""Generate the C++ weight header for the MLP policy (BC or RL).

Usage::

    python3 src/export_neural_cpp.py
    g++ -std=c++17 -O2 -DNEURAL_POLICY_DEMO cpp/neural_policy.cpp -o neural_demo

    python3 src/export_neural_cpp.py \
        --weights weights/rl_policy_weights.json \
        --out cpp/rl_policy_weights.hpp
    g++ -std=c++17 -O2 -DNEURAL_POLICY_USE_RL_WEIGHTS \
        -DNEURAL_POLICY_DEMO cpp/neural_policy.cpp -o rl_demo
"""
from __future__ import annotations

from paths import cpp_path, weights_path

import argparse
import json


def fmt(x: float) -> str:
    # 9 significant digits are enough for float32 source weights.
    return f"{float(x):.9g}f"


def array(values, per_line: int = 8) -> str:
    pieces = [fmt(x) for x in values]
    lines = [", ".join(pieces[i:i + per_line]) for i in range(0, len(pieces), per_line)]
    return ",\n    ".join(lines)


def matrix(rows, per_line: int = 8) -> str:
    body = ",\n    ".join("{" + array(row, per_line) + "}" for row in rows)
    return "{\n    " + body + "\n}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--weights", default=weights_path("neural_policy_weights.json"))
    ap.add_argument("--out", default=cpp_path("neural_policy_weights.hpp"))
    args = ap.parse_args()

    with open(args.weights, encoding="utf-8") as fh:
        w = json.load(fh)

    layers = w["layers"]
    if len(layers) != 3:
        raise SystemExit(f"expected 3 linear layers, got {len(layers)}")
    n_features = int(w["n_features"])
    n0 = len(layers[0]["w"])
    n1 = len(layers[1]["w"])

    lines = [
        "// Auto-generated by export_neural_cpp.py.  Do not edit by hand.",
        "#pragma once",
        "",
        "namespace neural_policy_weights {",
        f"constexpr int N_FEATURES = {n_features};",
        f"constexpr int N_HIDDEN0 = {n0};",
        f"constexpr int N_HIDDEN1 = {n1};",
        f"constexpr double TEMPERATURE = {float(w.get('temperature', 1.0)):.9g};",
        f"constexpr bool SAFE = {'true' if w.get('safe', True) else 'false'};",
        "",
        "static const float MEAN[N_FEATURES] = {",
        "    " + array(w["feature_mean"], 10),
        "};",
        "",
        "static const float STD[N_FEATURES] = {",
        "    " + array(w["feature_std"], 10),
        "};",
        "",
        f"static const float W0[N_HIDDEN0][N_FEATURES] = " + matrix(layers[0]["w"]) + ";",
        "",
        f"static const float B0[N_HIDDEN0] = {{",
        "    " + array(layers[0]["b"], 8),
        "};",
        "",
        f"static const float W1[N_HIDDEN1][N_HIDDEN0] = " + matrix(layers[1]["w"]) + ";",
        "",
        f"static const float B1[N_HIDDEN1] = {{",
        "    " + array(layers[1]["b"], 8),
        "};",
        "",
        f"static const float W2[N_HIDDEN1] = {{",
        "    " + array(layers[2]["w"][0], 8),
        "};",
        "",
        "static const float B2 = " + fmt(layers[2]["b"][0]) + ";",
        "",
        "}  // namespace neural_policy_weights",
        "",
    ]
    text = "\n".join(lines)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"written {args.out} ({len(text)} bytes, "
          f"{n_features}->{n0}->{n1}->1)")


if __name__ == "__main__":
    main()
