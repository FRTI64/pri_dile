#!/usr/bin/env python3
"""Generate the C++ weight header for the GRU-Net policy.

Usage::

    python3 src/export_gru_cpp.py
    g++ -std=c++17 -O2 -DGRU_POLICY_DEMO gru_policy.cpp -o gru_demo
"""
from __future__ import annotations

from paths import cpp_path, weights_path

import argparse
import json


def fmt(x: float) -> str:
    return f"{float(x):.9g}f"


def array(values, per_line: int = 8) -> str:
    pieces = [fmt(x) for x in values]
    lines = [", ".join(pieces[i:i + per_line])
             for i in range(0, len(pieces), per_line)]
    return ",\n    ".join(lines)


def matrix(rows, per_line: int = 8) -> str:
    body = ",\n    ".join("{" + array(row, per_line) + "}" for row in rows)
    return "{\n    " + body + "\n}"


def tensor(layers, per_line: int = 8) -> str:
    body = ",\n    ".join(matrix(layer, per_line) for layer in layers)
    return "{\n    " + body + "\n}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--weights", default=weights_path("gru_policy_weights.json"))
    ap.add_argument("--out", default=cpp_path("gru_policy_weights.hpp"))
    args = ap.parse_args()

    with open(args.weights, encoding="utf-8") as fh:
        w = json.load(fh)
    if w.get("format") != "ipd-gru-policy-v1":
        raise SystemExit(f"unexpected format: {w.get('format')}")

    n_features = int(w["n_features"])
    hidden = int(w["hidden"])
    num_layers = int(w["num_layers"])
    layers = w["gru"]
    if len(layers) != num_layers:
        raise SystemExit("num_layers does not match gru layer list")
    if num_layers != 1:
        raise SystemExit(
            "the C++ GRU port currently supports one layer; "
            "train with --layers 1 or use the Python GRUPolicy")
    for i, layer in enumerate(layers):
        if len(layer["weight_ih"]) != 3 * hidden:
            raise SystemExit(f"layer {i}: expected 3*hidden gate rows")
        if len(layer["weight_hh"]) != 3 * hidden:
            raise SystemExit(f"layer {i}: expected 3*hidden hidden rows")
    if len(w["head"]) != 2:
        raise SystemExit("expected a 2-layer MLP head")
    if len(w["head"][0]["w"]) != hidden or len(w["head"][0]["w"][0]) != hidden:
        raise SystemExit("head hidden layer shape mismatch")
    if len(w["head"][1]["w"]) != 1 or len(w["head"][1]["w"][0]) != hidden:
        raise SystemExit("head output layer shape mismatch")

    lines = [
        "// Auto-generated by export_gru_cpp.py.  Do not edit by hand.",
        "#pragma once",
        "",
        "namespace gru_policy_weights {",
        f"constexpr int N_FEATURES = {n_features};",
        f"constexpr int HIDDEN = {hidden};",
        f"constexpr int NUM_LAYERS = {num_layers};",
        f"constexpr double TEMPERATURE = {float(w.get('temperature', 1.0)):.9g};",
        "",
        "static const float MEAN[N_FEATURES] = {",
        "    " + array(w["feature_mean"], 10),
        "};",
        "",
        "static const float STD[N_FEATURES] = {",
        "    " + array(w["feature_std"], 10),
        "};",
        "",
        f"static const float W_IH[NUM_LAYERS][3 * HIDDEN][N_FEATURES] = "
        + tensor([layer["weight_ih"] for layer in layers]) + ";",
        "",
        f"static const float W_HH[NUM_LAYERS][3 * HIDDEN][HIDDEN] = "
        + tensor([layer["weight_hh"] for layer in layers]) + ";",
        "",
        "static const float B_IH[NUM_LAYERS][3 * HIDDEN] = {",
        ",\n    ".join("{" + array(layer["bias_ih"], 8) + "}" for layer in layers),
        "};",
        "",
        "static const float B_HH[NUM_LAYERS][3 * HIDDEN] = {",
        ",\n    ".join("{" + array(layer["bias_hh"], 8) + "}" for layer in layers),
        "};",
        "",
        "static const float HEAD_W0[HIDDEN][HIDDEN] = "
        + matrix(w["head"][0]["w"]) + ";",
        "",
        "static const float HEAD_B0[HIDDEN] = {",
        "    " + array(w["head"][0]["b"], 8),
        "};",
        "",
        "static const float HEAD_W1[HIDDEN] = {",
        "    " + array(w["head"][1]["w"][0], 8),
        "};",
        "",
        "static const float HEAD_B1 = " + fmt(w["head"][1]["b"][0]) + ";",
        "",
        "}  // namespace gru_policy_weights",
        "",
    ]
    text = "\n".join(lines)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"written {args.out} ({len(text)} bytes, "
          f"{n_features}->GRU({hidden})x{num_layers}->{hidden}->1)")


if __name__ == "__main__":
    main()
